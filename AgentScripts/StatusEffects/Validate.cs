using UnityEngine;
using UnityEditor;
using System;
using System.Linq;
using System.Collections.Generic;
using System.Reflection;
var results = new List<string>();
Action<bool,string> Check = (ok, label) => { results.Add((ok ? "PASS " : "FAIL ") + label); };
var p = Object.FindFirstObjectByType<PlayerStats>();
var c = p.GetComponent<StatusEffectController>();
var bag = p.GetComponent<Inventory>();
var hud = Object.FindFirstObjectByType<StatusEffectHUD>();
var poison = AssetDatabase.LoadAssetAtPath<StatusEffectDefinition>("Assets/StatusEffects/Poison.asset");
var slow = AssetDatabase.LoadAssetAtPath<StatusEffectDefinition>("Assets/StatusEffects/Slow.asset");
var bleed = AssetDatabase.LoadAssetAtPath<StatusEffectDefinition>("Assets/StatusEffects/Bleeding.asset");
var potion = AssetDatabase.LoadAssetAtPath<Consumable>("Assets/GamePlay/ScriptableObjects/Items/Consumables/Poison Potion.asset");
var advance = typeof(StatusEffectController).GetMethod("Advance", BindingFlags.Instance | BindingFlags.NonPublic);
Action<StatusEffectController,float> Tick = (target,dt) => advance.Invoke(target, new object[]{dt});
c.ClearAllEffects(); int health=p.currentHealth, max=p.maxHealth, armor=p.armor, damage=p.damage;
p.maxHealth=p.currentHealth=200; p.armor=0;
Check(bag.Count(potion) == 3,"Combat_Test supplies three Poison Potions");
int slot=bag.items.FindIndex(x=>x==potion); potion.Use(p.gameObject,slot);
Check(c.HasEffect("poison"),"inventory potion applies player Poison");
Check(bag.Count(potion)==2 && bag.items[slot]==null,"exactly one potion consumed");
Check(hud.transform.childCount==1,"HUD icon appears immediately");
int other=bag.items.FindIndex(x=>x==potion); Tick(c,2);
Check(p.currentHealth==198,"Poison first 2HP tick at two seconds");
float remain=c.GetRemainingDuration("poison"); potion.Use(p.gameObject,other);
Check(bag.Count(potion)==2,"duplicate potion retained"); Check(hud.GetComponentsInChildren<TMPro.TextMeshProUGUI>().Any(t=>t.text.Contains("already active")),"duplicate potion displays visible feedback");
Check(c.GetRemainingDuration("poison")==remain,"duplicate does not refresh timer");
Check(c.TryApplyEffect(poison)==StatusEffectApplyResult.AlreadyActive,"clear duplicate result");
Check(c.TryApplyEffect(slow)==StatusEffectApplyResult.Applied && c.TryApplyEffect(bleed)==StatusEffectApplyResult.Applied,"different effects coexist");
Check(Mathf.Approximately(p.MovementMultiplier,.6f),"player derived movement reduced to 60%");
Check(hud.transform.childCount>=3,"HUD has three effects");
Check(StatusEffectHUD.Description(c.ActiveEffects.First(x=>x.Id=="slow")).Contains("60%"),"tooltip contains speed modifier");
Tick(c,.5f); hud.SendMessage("Update");
Check(hud.GetComponentsInChildren<TMPro.TextMeshProUGUI>().Any(t=>t.text=="10s"),"HUD rounds fractional seconds up");
c.RemoveEffect("slow"); Check(p.MovementMultiplier==1 && c.HasEffect("bleeding"),"removing Slow restores speed while retaining Bleeding");
c.ClearAllEffects(); p.currentHealth=200;
c.TryApplyEffect(poison); Tick(c,15);
Check(p.currentHealth==186 && !c.HasEffect("poison"),"large-frame Poison catches seven ticks and expires");
c.TryApplyEffect(bleed); Tick(c,12);
Check(p.currentHealth==175 && !c.HasEffect("bleeding"),"Bleeding eleven ticks; no tick at expiration");
Check(hud.GetComponentsInChildren<TMPro.TextMeshProUGUI>().Length==0,"HUD icons hidden immediately on expiry");
Check(c.TryApplyEffect(null)==StatusEffectApplyResult.InvalidEffect,"null definition safe");
var invalid=ScriptableObject.CreateInstance<StatusEffectDefinition>(); invalid.effectId="invalid"; invalid.duration=float.NaN;
Check(c.TryApplyEffect(invalid)==StatusEffectApplyResult.InvalidEffect,"invalid duration safe"); Object.Destroy(invalid);
var weak=ScriptableObject.CreateInstance<StatusEffectDefinition>(); weak.effectId="test-weakness"; weak.duration=5; weak.outgoingDamageMultiplier=.75f; weak.incomingDamageMultiplier=2;
p.damage=20; c.TryApplyEffect(weak); Check(p.EffectiveDamage==15,"outgoing damage modifier"); p.TakeDamage(3); Check(p.currentHealth==169,"incoming damage modifier");
c.TryApplyEffect(slow); Tick(c,5); Check(p.EffectiveDamage==20 && Mathf.Approximately(p.MovementMultiplier,.6f),"modifier expiry retains independent Slow");
Tick(c,5); Check(p.MovementMultiplier==1,"Slow expiry restores derived speed"); Object.Destroy(weak);
c.TryApplyEffect(slow); c.enabled=false; Check(c.ActiveEffects.Count==0 && p.MovementMultiplier==1,"disabled controller clears modifiers");
Check(c.TryApplyEffect(poison)==StatusEffectApplyResult.InvalidTarget,"disabled target rejected"); c.enabled=true;
var healing=AssetDatabase.LoadAssetAtPath<Consumable>("Assets/GamePlay/ScriptableObjects/Items/Consumables/Health Potion.asset"); bag.Add(healing); int hs=bag.items.FindIndex(x=>x==healing); p.currentHealth=100; healing.Use(p.gameObject,hs);
Check(p.currentHealth==110 && bag.items[hs]==null,"healing potion remains functional");
var enemyPrefab=AssetDatabase.LoadAssetAtPath<GameObject>("Assets/Prefabs/Enemies/Enemy_Main.prefab");
var spawn=p.transform.position; if(UnityEngine.AI.NavMesh.SamplePosition(spawn,out var navHit,20,UnityEngine.AI.NavMesh.AllAreas)) spawn=navHit.position; var e=Object.Instantiate(enemyPrefab,spawn,Quaternion.identity); var es=e.GetComponent<EnemyStats>(); var ec=e.GetComponent<StatusEffectController>();
es.maxHealth=es.currentHealth=100; es.armor=0;
Check(ec.TryApplyEffect(poison,p.transform)==StatusEffectApplyResult.Applied,"Enemy_Main accepts shared Poison"); Tick(ec,2); Check(es.currentHealth==98,"enemy Poison damage through EnemyStats");
ec.TryApplyEffect(slow); Check(Mathf.Approximately(es.MovementMultiplier,.6f),"enemy derived movement reduced");
ec.TryApplyEffect(bleed); Tick(ec,1); Check(es.currentHealth==97,"enemy Bleeding uses same tick engine");
ec.ClearAllEffects(); Check(es.MovementMultiplier==1,"enemy modifier removal restores speed");
bool died=false; es.OnDeath += source=>died=source==p.transform; es.currentHealth=1; ec.TryApplyEffect(poison,p.transform); Tick(ec,2);
Check(es.IsDead && died && ec.ActiveEffects.Count==0,"DoT uses enemy death event, attribution and clears all effects");
Object.Destroy(e); c.ClearAllEffects(); p.currentHealth=health; p.maxHealth=max; p.armor=armor; p.damage=damage;
return new { passed=results.Count(x=>x.StartsWith("PASS")), failed=results.Count(x=>x.StartsWith("FAIL")), results };

